# Tests for check-verification-metadata-diff.py (issue #925). Stdlib only:
#   python3 -I -m unittest discover -s scripts -p 'test_*.py'
import importlib.util
import pathlib
import tempfile
import unittest

_SCRIPT = pathlib.Path(__file__).with_name("check-verification-metadata-diff.py")
_spec = importlib.util.spec_from_file_location("check_metadata", _SCRIPT)
checker = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(checker)

SHA_A = "a" * 64
SHA_B = "b" * 64
SHA_C = "c" * 64

CONFIG = """
   <configuration>
      <verify-metadata>true</verify-metadata>
      <verify-signatures>false</verify-signatures>
      <trusted-artifacts>
         <trust file=".*-sources[.]jar" regex="true"/>
      </trusted-artifacts>
   </configuration>"""


def component(gav, artifact, sha):
    group, name, version = gav.split(":")
    return f"""
      <component group="{group}" name="{name}" version="{version}">
         <artifact name="{artifact}">
            <sha256 value="{sha}" origin="Generated by Gradle"/>
         </artifact>
      </component>"""


def document(components, config=CONFIG):
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<verification-metadata xmlns="https://schema.gradle.org/dependency-verification">{config}
   <components>{"".join(components)}
   </components>
</verification-metadata>
"""


BASE = document([component("g:a:1", "a-1.jar", SHA_A)])


class CheckVerificationMetadataDiffTest(unittest.TestCase):
    def setUp(self):
        self.dir = tempfile.TemporaryDirectory()
        self.addCleanup(self.dir.cleanup)

    def write(self, name, text):
        path = pathlib.Path(self.dir.name, name)
        path.write_text(text, encoding="utf-8")
        return str(path)

    def verdict(self, candidate, base=BASE):
        return checker.main(
            ["check", self.write("base.xml", base), self.write("new.xml", candidate)]
        )

    def assert_rejected(self, candidate):
        self.assertEqual(self.verdict(candidate), 1)

    def test_identical_file_is_accepted(self):
        self.assertEqual(self.verdict(BASE), 0)

    def test_added_component_is_accepted(self):
        candidate = document(
            [component("g:a:1", "a-1.jar", SHA_A), component("g:b:2", "b-2.jar", SHA_B)]
        )
        self.assertEqual(self.verdict(candidate), 0)

    def test_added_artifact_on_existing_component_is_accepted(self):
        candidate = BASE.replace(
            "</component>",
            f'<artifact name="a-1.pom"><sha256 value="{SHA_C}" origin="Generated by Gradle"/>'
            "</artifact></component>",
        )
        self.assertEqual(self.verdict(candidate), 0)

    def test_changed_checksum_is_rejected(self):
        self.assert_rejected(document([component("g:a:1", "a-1.jar", SHA_B)]))

    def test_extra_checksum_on_existing_artifact_is_rejected(self):
        self.assert_rejected(
            BASE.replace("</artifact>", f'<sha256 value="{SHA_B}" origin="x"/></artifact>')
        )

    def test_removed_component_is_rejected(self):
        self.assert_rejected(document([component("g:b:2", "b-2.jar", SHA_B)]))

    def test_disabling_verification_is_rejected(self):
        self.assert_rejected(
            BASE.replace(
                "<verify-metadata>true</verify-metadata>",
                "<verify-metadata>false</verify-metadata>",
            )
        )

    def test_new_trusted_artifact_rule_is_rejected(self):
        self.assert_rejected(
            BASE.replace("</trusted-artifacts>", '<trust group=".*" regex="true"/></trusted-artifacts>')
        )

    def test_added_trusted_keys_section_is_rejected(self):
        self.assert_rejected(
            BASE.replace(
                "</configuration>",
                '<trusted-keys><trusted-key id="ABCDEF" group="g"/></trusted-keys></configuration>',
            )
        )

    def test_added_component_with_non_checksum_child_is_rejected(self):
        candidate = BASE.replace(
            "</components>",
            '<component group="g" name="c" version="3"><artifact name="c-3.jar">'
            '<ignored-keys><ignored-key id="ABCDEF"/></ignored-keys></artifact></component>'
            "</components>",
        )
        self.assert_rejected(candidate)

    def test_added_component_with_malformed_checksum_is_rejected(self):
        self.assert_rejected(
            document([component("g:a:1", "a-1.jar", SHA_A), component("g:b:2", "b-2.jar", "nothex")])
        )

    def test_doctype_is_rejected(self):
        self.assert_rejected(
            BASE.replace(
                '<?xml version="1.0" encoding="UTF-8"?>',
                '<?xml version="1.0"?><!DOCTYPE x [<!ENTITY e "x">]>',
            )
        )

    def test_malformed_xml_is_rejected(self):
        self.assert_rejected(BASE.replace("</components>", ""))

    def test_foreign_root_is_rejected(self):
        self.assert_rejected('<?xml version="1.0"?><something-else/>')


class AgainstDefaultBranchTest(CheckVerificationMetadataDiffTest):
    """--allow-missing: the baseline is main's file, the branch may be behind it."""

    def verdict(self, candidate, base=BASE):
        return checker.main(
            [
                "check",
                "--allow-missing",
                self.write("base.xml", base),
                self.write("new.xml", candidate),
            ]
        )

    def test_removed_component_is_rejected(self):
        # Inherited expectation does not hold here: see the test below.
        pass

    def test_component_missing_relative_to_main_is_accepted(self):
        main = document(
            [component("g:a:1", "a-1.jar", SHA_A), component("g:m:9", "m-9.jar", SHA_C)]
        )
        self.assertEqual(self.verdict(BASE, base=main), 0)

    def test_weakening_committed_on_the_branch_is_still_rejected(self):
        # The branch's own file already disables verification; against main the
        # candidate (which carries that change) must fail.
        weakened = BASE.replace(
            "<verify-metadata>true</verify-metadata>",
            "<verify-metadata>false</verify-metadata>",
        )
        self.assertEqual(self.verdict(weakened), 1)

    def test_checksum_changed_relative_to_main_is_rejected(self):
        self.assertEqual(self.verdict(document([component("g:a:1", "a-1.jar", SHA_B)])), 1)


if __name__ == "__main__":
    unittest.main()
