# Office-converter smoke test (issue #908): proves the LibreOffice subprocess in the
# built image still converts with the isolated environment and the hardened per-run
# profile — a DOCX upload is ingested (DOCX -> PDF -> extraction), its PDF rendition
# is served, and an annotation export renders to PDF.
#
# Runs after scripts/smoke-test.sh (which seeds the database) and after the
# Playwright screenshot run, so the extra review it creates cannot change any
# baseline. Fails fast (non-zero exit) on the first deviation.
#
#   bash scripts/smoke-office.sh
#
# Needs bash, curl, jq, cmp and head on PATH.
set -euo pipefail

BASE_URL="${SMOKE_BASE_URL:-http://localhost:8080}"
SAMPLE_DOCX="testdata/documents/sample.docx" # generated by scripts/make-sample-docx.py
DOCX_TYPE="application/vnd.openxmlformats-officedocument.wordprocessingml.document"
SEED_USER="admin"
SEED_PASS="Test-Pass-1234!"
# A cold LibreOffice start plus the scheduled extraction job: allow a few minutes.
EXTRACT_RETRIES=36
EXTRACT_DELAY=5

WORKDIR="$(mktemp -d)"
trap 'rm -rf "${WORKDIR}"' EXIT

log() { echo "[smoke-office] $*"; }
fail() {
  echo "[smoke-office] FAIL: $*" >&2
  exit 1
}

TOKEN=""
aget() { curl -sf "${BASE_URL}$1" -H "Authorization: Bearer ${TOKEN}"; }
is_pdf() { [ "$(head -c 5 "$1")" = "%PDF-" ]; }

# 1) Login as the seeded admin.
TOKEN="$(
  curl -sf -X POST "${BASE_URL}/api/v1/auth/login" \
    -H 'Content-Type: application/json' \
    -d "{\"usernameOrEmail\":\"${SEED_USER}\",\"password\":\"${SEED_PASS}\"}" |
    jq -r '.accessToken'
)"
[ -n "$TOKEN" ] && [ "$TOKEN" != "null" ] || fail "login did not return an access token"
log "logged in"

# 2) The image ships LibreOffice, so the server must report both converter-backed
#    capabilities; if the probe failed, everything below would be refused anyway.
config="$(curl -sf "${BASE_URL}/api/v1/config")"
echo "$config" | jq -e '[.supportedFormats[] | ascii_downcase] | index("docx")' >/dev/null ||
  fail "supportedFormats lacks docx: $(echo "$config" | jq -c '.supportedFormats')"
echo "$config" | jq -e '[.exportFormats[] | ascii_downcase] | index("pdf")' >/dev/null ||
  fail "exportFormats lacks pdf: $(echo "$config" | jq -c '.exportFormats')"
log "GET /api/v1/config -> docx ingest and pdf export available"

# 3) Upload the DOCX fixture.
upload_json="$(
  curl -sf -X POST "${BASE_URL}/api/v1/documents" \
    -H "Authorization: Bearer ${TOKEN}" \
    -F "title=Smoke DOCX Review" \
    -F "file=@${SAMPLE_DOCX};type=${DOCX_TYPE}"
)" || fail "DOCX upload was refused"
doc_id="$(echo "$upload_json" | jq -r '.documentId')"
[ -n "$doc_id" ] && [ "$doc_id" != "null" ] || fail "DOCX upload did not return a documentId"
log "POST /api/v1/documents (DOCX) -> document ${doc_id}"

# 4) Conversion + extraction reach READY.
extraction=""
for i in $(seq 1 "$EXTRACT_RETRIES"); do
  extraction="$(aget "/api/v1/documents/${doc_id}/versions" | jq -r '.versions[0].extractionStatus')"
  [ "$extraction" = "READY" ] && break
  [ "$extraction" = "FAILED" ] && fail "DOCX extraction FAILED (see the qnop container log)"
  if [ "$i" -eq "$EXTRACT_RETRIES" ]; then
    fail "DOCX extraction did not reach READY within $((EXTRACT_RETRIES * EXTRACT_DELAY))s (last=${extraction})"
  fi
  sleep "$EXTRACT_DELAY"
done
log "DOCX conversion + extraction READY"

# 5) The extracted text is the fixture's.
text="$(aget "/api/v1/documents/${doc_id}/versions/1/rendered" | jq -r '[.surfaces[].textSpans[].text] | join("")')"
echo "$text" | grep -q "QNOP" || fail "rendered DOCX text '${text}' does not contain the fixture text"
log "GET .../rendered -> '${text}'"

# 6) The PDF rendition is served; the original is the uploaded Word file.
aget "/api/v1/documents/${doc_id}/versions/1/rendition" >"${WORKDIR}/rendition.pdf" ||
  fail "GET .../rendition failed"
is_pdf "${WORKDIR}/rendition.pdf" || fail "the rendition is not a PDF"
aget "/api/v1/documents/${doc_id}/versions/1/original" >"${WORKDIR}/original.docx" ||
  fail "GET .../original failed"
cmp -s "${WORKDIR}/original.docx" "$SAMPLE_DOCX" ||
  fail "streamed original is not byte-identical to the uploaded DOCX"
log "GET .../rendition -> PDF; GET .../original -> the uploaded DOCX"

# 7) The annotation export renders to PDF through the same converter.
aget "/api/v1/documents/${doc_id}/annotations/export?format=pdf" >"${WORKDIR}/export.pdf" ||
  fail "GET .../annotations/export?format=pdf failed"
is_pdf "${WORKDIR}/export.pdf" || fail "the annotation export is not a PDF"
log "GET .../annotations/export?format=pdf -> PDF ($(wc -c <"${WORKDIR}/export.pdf") bytes)"

log "ALL OFFICE SMOKE CHECKS PASSED"
